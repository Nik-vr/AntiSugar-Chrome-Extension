// Информация о компоненте по найденному ключевому слова (с транслитерацией кириллицы)
function asgComponentInfo(keyword) {
  if (typeof ASG_COMPONENTS === 'undefined' || !ASG_COMPONENTS) return null;
  const direct = ASG_COMPONENTS[keyword];
  if (direct) return direct;
  if (typeof asgTranslit === 'function') {
    const t = asgTranslit(String(keyword || '').toLowerCase());
    for (const [k, v] of Object.entries(ASG_COMPONENTS)) {
      if (asgTranslit(k) === t) return v;
    }
  }
  return null;
}
