// Решение по верхней категории товара.
//   'food'    — раздел из списка продовольственных, товар оцениваем;
//   'notFood' — раздел из списка непищевых, не оцениваем;
//   'unknown' — раздел не опознан: списков недостаточно, решение принимает
//               фон по содержимому страницы (см. foodDecision в background.js).
// Порядок: чёрный список главнее белого — «Здоровое питание» есть в обоих
// списках, и побеждает запрет.
// Категория вне обоих списков — не приговор: на Ozon конфеты и батончики
// лежат в «Спорт и отдых», а протеиновые смеси — в «Здоровье». Такие разделы
// оцениваются по составу: если в блоке «Состав» есть сахар или
// подсластители, перед нами еда независимо от раздела.
function asgCategoryDecision(name, foodCategories, nonFoodCategories) {
  const norm = (v) =>
    String(v || '')
      .replace(/[\u00AD\u200B-\u200D\u2060\uFEFF]/g, '')
      .replace(/\s+/g, ' ')
      .trim()
      .toLowerCase();
  const n = norm(name);
  if (!n) return 'unknown';
  const food = (foodCategories || []).map(norm).filter(Boolean);
  const bad = (nonFoodCategories || []).map(norm).filter(Boolean);
  if (bad.some((c) => n.includes(c))) return 'notFood';
  if (food.length && food.some((c) => n.includes(c))) return 'food';
  return 'unknown';
}
